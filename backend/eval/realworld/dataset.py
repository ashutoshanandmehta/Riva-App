"""Real-world eval dataset: on-disk layout, ground-truth schema, and discovery.

Layout (one directory per dish under dataset/):
    dataset/<dish_id>/
        capture.mp4        the 3-5s arc clip  (or: frames/ with stills)
        truth.json         REQUIRED ground truth (schema below)
        arkit_poses.json   OPTIONAL per-frame camera pose + intrinsics (ARKit path)
        frames/            GENERATED by ingest.py (sharpest frames)

truth.json:
    {
      "dish_id": "d001",                      required, matches dir name
      "name": "chipotle chicken bowl",        required
      "grams_total": 540,                     required — kitchen-scale ground truth
      "components": [                          optional — per-ingredient weights
          {"name": "brown rice", "grams": 180},
          {"name": "grilled chicken", "grams": 150}
      ],
      "kcal_total": 640,                       optional — measured/known calories
      "container": {"type": "bowl", "diameter_cm": 20.3},   optional scale anchor
      "scale_reference": {"type": "credit_card", "long_mm": 85.6},  optional
      "hint": "chipotle chicken bowl, olive oil",  optional user text hint
      "device": "iphone15pro", "arkit": false,     optional metadata
      "notes": ""
    }
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATASET = HERE / "dataset"

REQUIRED = ("dish_id", "name", "grams_total")


def validate_truth(truth: dict, dir_name: str) -> list[str]:
    """Returns a list of problems (empty = valid)."""
    errs = []
    for key in REQUIRED:
        if key not in truth:
            errs.append(f"missing required field '{key}'")
    if "dish_id" in truth and truth["dish_id"] != dir_name:
        errs.append(f"dish_id '{truth['dish_id']}' != directory '{dir_name}'")
    g = truth.get("grams_total")
    if g is not None and (not isinstance(g, (int, float)) or g <= 0):
        errs.append(f"grams_total must be a positive number, got {g!r}")
    comps = truth.get("components")
    if comps is not None:
        if not isinstance(comps, list) or any("grams" not in c for c in comps):
            errs.append("components must be a list of {name, grams}")
    return errs


def discover(dataset_dir: Path = DATASET) -> list[dict]:
    """Find every dish dir with a truth.json. Returns dicts with paths + truth,
    plus a `problems` list per dish (validation + missing capture)."""
    out = []
    if not dataset_dir.exists():
        return out
    for d in sorted(p for p in dataset_dir.iterdir() if p.is_dir()):
        tpath = d / "truth.json"
        if not tpath.exists():
            continue
        problems = []
        try:
            truth = json.loads(tpath.read_text())
        except json.JSONDecodeError as e:
            out.append({"dish_id": d.name, "dir": d, "truth": None,
                        "problems": [f"truth.json invalid JSON: {e}"]})
            continue
        problems += validate_truth(truth, d.name)
        video = d / "capture.mp4"
        stills = d / "frames"
        has_stills = stills.exists() and any(stills.glob("*.jp*g"))
        if not video.exists() and not has_stills:
            problems.append("no capture.mp4 and no frames/*.jpg")
        out.append({
            "dish_id": d.name, "dir": d, "truth": truth,
            "video": video if video.exists() else None,
            "frames_dir": stills, "problems": problems,
        })
    return out
